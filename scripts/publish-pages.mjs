// Publish only generated static files; preserve the source checkout and Git index.
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, lstatSync } from 'node:fs';
import { join } from 'node:path';

function git(args, input) {
  return execFileSync('git', args, { input, encoding: input instanceof Buffer ? undefined : 'utf8', stdio: ['pipe', 'pipe', 'pipe'] });
}
function text(args) { return String(git(args)).trim(); }
if (text(['status', '--porcelain'])) throw new Error('Commit source changes before publishing.');
readFileSync('dist/index.html');
const source = text(['rev-parse', '--verify', 'HEAD^{commit}']);
const remoteRef = text(['ls-remote', '--heads', 'origin', 'refs/heads/gh-pages']);
const previous = remoteRef ? remoteRef.split(/\s+/)[0] : null;
if (previous) {
  git(['fetch', 'origin', 'refs/heads/gh-pages']);
  try { git(['cat-file', '-e', `${previous}:.entre-prototype`]); }
  catch { throw new Error('Existing gh-pages branch is not generated by this project; refusing to replace it.'); }
}
const blob = input => textWithInput(['hash-object', '-w', '--stdin'], input);
function textWithInput(args, input) { return String(git(args, input)).trim(); }
function tree(directory, root = false) {
  const entries = readdirSync(directory).sort().map(name => {
    const path = join(directory, name);
    const stat = lstatSync(path);
    if (stat.isSymbolicLink()) throw new Error(`Symlink not allowed in deployment: ${path}`);
    if (stat.isDirectory()) return `040000 tree ${tree(path)}\t${name}\0`;
    if (!stat.isFile()) throw new Error(`Unsupported build entry: ${path}`);
    return `100644 blob ${blob(readFileSync(path))}\t${name}\0`;
  });
  if (root) {
    entries.push(`100644 blob ${blob(Buffer.alloc(0))}\t.nojekyll\0`);
    entries.push(`100644 blob ${blob(Buffer.from(`Generated Entre prototype from ${source}\n`))}\t.entre-prototype\0`);
  }
  return textWithInput(['mktree', '-z'], Buffer.from(entries.join('')));
}
const args = ['commit-tree', tree('dist', true)];
if (previous) args.push('-p', previous);
const commit = textWithInput(args, `Publish Entre prototype from ${source}\n`);
execFileSync('git', ['push', 'origin', `${commit}:refs/heads/gh-pages`], { stdio: 'inherit' });
console.log('Static build uploaded to gh-pages. GitHub Pages must be enabled for that branch and root directory.');
console.log('Uploading a branch alone does not confirm that the public website is live.');
