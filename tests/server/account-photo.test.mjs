import test from 'node:test';
import assert from 'node:assert/strict';
import sharp from 'sharp';
import { fixture } from './feature-fixture.mjs';
import { DatabaseSync } from 'node:sqlite';

test('foto privada propia y requisito en nuevas conexiones sin interrumpir conversaciones existentes', async t => {
  const options = { plazaEnabled: true, requireConnectionPhoto: false };
  const f = await fixture(t, options);
  const a = await f.signup('photo_a'), b = await f.signup('photo_b'), c = await f.signup('photo_c');
  const post = await f.request('/api/plaza/posts', 'POST', { topic:'crear', title:'Hola', body:'Conversación' }, a.cookie);
  const old = await f.request('/api/plaza/invitations','POST',{kind:'post',contentId:post.body.post.id,note:''},b.cookie);
  assert.equal((await f.request(`/api/plaza/invitations/${old.body.invitation.id}/decision`,'POST',{action:'accept'},a.cookie)).status,200);
  options.requireConnectionPhoto = true; await f.restart();
  assert.equal((await f.request(`/api/plaza/connections/${old.body.invitation.id}/messages`,'POST',{clientId:'photo-old-001',body:'Hola'},a.cookie)).status,201);
  assert.equal((await f.request('/api/plaza/invitations','POST',{kind:'post',contentId:post.body.post.id,note:''},c.cookie)).status,403);
  const bytes=await sharp({create:{width:40,height:40,channels:3,background:'#285d4c'}}).png().toBuffer();
  const upload = (cookie, declaration, origin='http://localhost:4173') => f.raw('/api/account/profile/photo',{method:'POST',headers:{Origin:origin,Cookie:cookie,'Content-Type':'image/png','X-Photo-Declaration':declaration},body:bytes});
  assert.equal((await upload(c.cookie,'no')).status,422);
  assert.equal((await upload(c.cookie,'yes','https://otro.test')).status,403);
  assert.equal((await upload(c.cookie,'yes')).status,201);
  assert.equal((await f.raw('/api/account/profile/photo',{headers:{Cookie:c.cookie}})).status,200);
  assert.equal((await f.raw('/api/account/profile/photo',{headers:{Cookie:b.cookie}})).status,404);
  const invite=await f.request('/api/plaza/invitations','POST',{kind:'post',contentId:post.body.post.id,note:''},c.cookie);
  assert.equal(invite.status,201);
  assert.equal((await f.request(`/api/plaza/invitations/${invite.body.invitation.id}/decision`,'POST',{action:'accept'},a.cookie)).status,403);
  assert.equal((await upload(a.cookie,'yes')).status,201);
  assert.equal((await f.request(`/api/plaza/invitations/${invite.body.invitation.id}/decision`,'POST',{action:'accept'},a.cookie)).status,200);
  const share=`/api/plaza/connections/${invite.body.invitation.id}/profile-photo`;
  assert.equal((await f.raw(share+'/image',{headers:{Cookie:a.cookie}})).status,404);
  assert.equal((await f.request(share,'POST',{action:'share'},c.cookie)).status,200);
  assert.equal((await f.raw(share+'/image',{headers:{Cookie:a.cookie}})).status,200);
  assert.equal((await f.raw(share+'/image',{headers:{Cookie:b.cookie}})).status,404);
  assert.equal((await f.request(share,'POST',{action:'revoke'},c.cookie)).status,200);
  assert.equal((await f.raw(share+'/image',{headers:{Cookie:a.cookie}})).status,404);
  assert.equal((await f.request(share,'POST',{action:'share'},c.cookie)).status,200);
  assert.equal((await upload(c.cookie,'yes')).status,201);
  assert.equal((await f.raw(share+'/image',{headers:{Cookie:a.cookie}})).status,404);
  assert.equal((await f.request(share,'POST',{action:'share'},c.cookie)).status,200);
  assert.equal((await f.raw('/api/account/profile/photo',{method:'DELETE',headers:{Origin:'http://localhost:4173',Cookie:c.cookie}})).status,200);
  assert.equal((await f.raw('/api/account/profile/photo',{headers:{Cookie:c.cookie}})).status,404);
  assert.equal((await f.raw(share+'/image',{headers:{Cookie:a.cookie}})).status,404);
  assert.equal((await upload(c.cookie,'yes')).status,201);
  assert.equal((await f.request(share,'POST',{action:'share'},c.cookie)).status,200);
  assert.equal((await f.request(`/api/plaza/connections/${invite.body.invitation.id}/block`,'POST',{},a.cookie)).status,200);
  assert.equal((await f.raw(share+'/image',{headers:{Cookie:a.cookie}})).status,404);
});

test('una foto compartida puede reportarse con evidencia y moderarse sin afectar una foto posterior', async t => {
  const f=await fixture(t,{plazaEnabled:true,requireConnectionPhoto:true});
  const a=await f.signup('photo_report_a'), b=await f.signup('photo_report_b'), mod=await f.signup('photo_report_mod');
  const db=new DatabaseSync(f.path); db.prepare('INSERT INTO moderators(user_id) VALUES(?)').run(mod.id); db.close();
  const bytes=await sharp({create:{width:40,height:40,channels:3,background:'#285d4c'}}).png().toBuffer();
  for (const p of [a,b]) assert.equal((await f.raw('/api/account/profile/photo',{method:'POST',headers:{Origin:'http://localhost:4173',Cookie:p.cookie,'Content-Type':'image/png','X-Photo-Declaration':'yes'},body:bytes})).status,201);
  const post=(await f.request('/api/plaza/posts','POST',{topic:'crear',title:'Hola',body:'Conversación'},a.cookie)).body.post;
  const inv=(await f.request('/api/plaza/invitations','POST',{kind:'post',contentId:post.id,note:''},b.cookie)).body.invitation;
  await f.request(`/api/plaza/invitations/${inv.id}/decision`,'POST',{action:'accept'},a.cookie);
  const share=`/api/plaza/connections/${inv.id}/profile-photo`;
  await f.request(share,'POST',{action:'share'},b.cookie);
  const state=(await f.request(share,'GET',undefined,a.cookie)).body;
  assert.ok(state.theirsId);
  const report=await f.request('/api/plaza/reports','POST',{kind:'profile_photo',contentId:state.theirsId,reason:'spam',note:''},a.cookie);
  assert.equal(report.status,201);
  assert.equal((await f.raw(`/api/plaza/moderation/images/${report.body.id}`,{headers:{Cookie:mod.cookie}})).status,200);
  const decision=await f.request('/api/plaza/moderation/actions','POST',{reportId:report.body.id,action:'hide',reason:'Contenido no permitido'},mod.cookie);
  assert.equal(decision.status,200);
  assert.equal((await f.raw(share+'/image',{headers:{Cookie:a.cookie}})).status,404);
  assert.equal((await f.raw('/api/account/profile/photo',{method:'POST',headers:{Origin:'http://localhost:4173',Cookie:b.cookie,'Content-Type':'image/png','X-Photo-Declaration':'yes'},body:bytes})).status,422);
  const replacement=await sharp({create:{width:40,height:40,channels:3,background:'#a46743'}}).png().toBuffer();
  assert.equal((await f.raw('/api/account/profile/photo',{method:'POST',headers:{Origin:'http://localhost:4173',Cookie:b.cookie,'Content-Type':'image/png','X-Photo-Declaration':'yes'},body:replacement})).status,201);
  assert.equal((await f.request(share,'POST',{action:'share'},b.cookie)).status,200);
  assert.equal((await f.raw(share+'/image',{headers:{Cookie:a.cookie}})).status,200);
});
