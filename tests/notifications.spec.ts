import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { seedPosts } from "../src/plaza/data";
const song = seedPosts[0].title;
test("centro vacío sin actividad inventada; prueba explícita, lectura y regreso al comentario", async ({page}) => {
  const api:string[]=[];page.on('request',r=>{if(r.url().includes('/api/'))api.push(r.url());});
  await page.goto('/');
  await page.getByRole('button',{name:'Notificaciones, sin avisos sin leer',exact:true}).click();
  const center=page.getByRole('dialog',{name:'Notificaciones',exact:true});
  await expect(center.getByText('No tienes avisos nuevos.',{exact:true})).toBeVisible();
  await center.getByText('Probar las notificaciones de la maqueta',{exact:true}).click();await center.getByRole('button',{name:'Probar un aviso de ejemplo',exact:true}).click();
  await expect(center.getByText('Aviso de ejemplo',{exact:true})).toHaveCount(1);
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  await page.keyboard.press('Escape');
  const bell=page.getByRole('button',{name:'Notificaciones, 1 aviso sin leer',exact:true});
  await expect(bell).toBeFocused();await bell.click();
  await center.getByRole('button',{name:`Abrir aviso sobre ${song}`,exact:true}).click();
  const thread=page.getByRole('dialog',{name:song,exact:true});await expect(thread).toBeVisible();
  await expect(thread.locator('[tabindex="-1"]:focus')).toHaveCount(1);
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button',{name:'Notificaciones, sin avisos sin leer',exact:true})).toBeVisible();
  expect(api).toEqual([]);
});
