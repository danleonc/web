test('un aviso abierto desde el worker cierra la guía y deja operativo el centro',async({page})=>{
 await page.goto('/');await page.getByRole('button',{name:'Ver recorrido',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Conoce Nexafia',exact:true})).toBeVisible();
 await page.evaluate(async()=>{const registration=await navigator.serviceWorker.ready;navigator.serviceWorker.dispatchEvent(new MessageEvent('message',{data:{type:'nexafia-open-notifications'},source:registration.active}));});
 await expect(page.getByRole('dialog',{name:'Conoce Nexafia',exact:true})).toHaveCount(0);
 const center=page.getByRole('dialog',{name:'Notificaciones',exact:true});await expect(center).toBeVisible();
 await center.getByRole('button',{name:'Cerrar ventana',exact:true}).click();await expect(center).toHaveCount(0);
});
